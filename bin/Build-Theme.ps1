#Requires -Version 7
# Reads themes/<name>/colors.toml (flat key = "value" pairs, same 31 keys
# Omarchy themes use) and generates the per-app theme files it feeds:
# YASB styles.css, komorebi.json border colors, alacritty.toml colors,
# btop.conf theme. Mirrors Omarchy's single-palette-source theme design
# (~/.local/state/omarchy/current/theme/colors.toml -> per-app generated
# files) without a generic TOML dependency, since this file's shape is
# flat key = "value" lines only.
#
# Usage: ./bin/Build-Theme.ps1 -Theme tokyo-night
param(
    [string]$Theme = 'tokyo-night'
)
$ErrorActionPreference = 'Stop'
Set-Location "$PSScriptRoot/.."

$tomlPath = "themes/$Theme/colors.toml"
if (-not (Test-Path $tomlPath)) {
    Write-Error "no such theme: $tomlPath"
    exit 1
}

$colors = @{}
Get-Content $tomlPath | ForEach-Object {
    if ($_ -match '^\s*([a-z_]+)\s*=\s*"([^"]*)"\s*$') {
        $colors[$Matches[1]] = $Matches[2]
    }
}

function ConvertTo-KomorebiColour {
    # komorebi.json border_colours entries are {r, g, b} ints, not hex strings.
    param([string]$Hex)
    $Hex = $Hex.TrimStart('#')
    return @{
        r = [Convert]::ToInt32($Hex.Substring(0,2), 16)
        g = [Convert]::ToInt32($Hex.Substring(2,2), 16)
        b = [Convert]::ToInt32($Hex.Substring(4,2), 16)
    }
}

Write-Host "==> Building theme files from $tomlPath"

# --- YASB styles.css ---------------------------------------------------
$cssVars = ($colors.GetEnumerator() | ForEach-Object { "  --$($_.Key.Replace('_','-')): $($_.Value);" }) -join "`n"
$css = @"
/* Generated by bin/Build-Theme.ps1 from themes/$Theme/colors.toml -- do not edit by hand. */
:root {
$cssVars
}

* {
  font-family: "CaskaydiaCove Nerd Font", "Segoe UI", sans-serif;
}

.yasb-bar {
  background-color: var(--background);
  color: var(--foreground);
}

.widget {
  color: var(--foreground);
}

.widget:hover {
  color: var(--bright-foreground);
  background-color: var(--selection);
}

.komorebi-workspaces .ws-active {
  color: var(--accent);
}
"@
Set-Content -Path 'yasb/.config/yasb/styles.css' -Value $css
Write-Host "    -> yasb/.config/yasb/styles.css"

# --- komorebi.json border colours --------------------------------------
$komorebiPath = 'komorebi/.config/komorebi/komorebi.json'
$komorebi = Get-Content $komorebiPath -Raw | ConvertFrom-Json -AsHashtable
$komorebi.border_colours = @{
    single    = ConvertTo-KomorebiColour $colors.accent
    stack     = ConvertTo-KomorebiColour $colors.magenta
    monocle   = ConvertTo-KomorebiColour $colors.green
    unfocused = ConvertTo-KomorebiColour $colors.muted
}
$komorebi | ConvertTo-Json -Depth 10 | Set-Content -Path $komorebiPath
Write-Host "    -> $komorebiPath (border_colours)"

# --- alacritty.toml colors ----------------------------------------------
$alacrittyColors = @"
# Generated by bin/Build-Theme.ps1 from themes/$Theme/colors.toml -- colors
# section only; everything else in alacritty.toml is hand-written.
[colors.primary]
background = "$($colors.background)"
foreground = "$($colors.foreground)"

[colors.normal]
black   = "$($colors.dark_background)"
red     = "$($colors.red)"
green   = "$($colors.green)"
yellow  = "$($colors.yellow)"
blue    = "$($colors.blue)"
magenta = "$($colors.magenta)"
cyan    = "$($colors.cyan)"
white   = "$($colors.foreground)"

[colors.bright]
black   = "$($colors.dark_foreground)"
red     = "$($colors.bright_red)"
green   = "$($colors.bright_green)"
yellow  = "$($colors.bright_yellow)"
blue    = "$($colors.bright_blue)"
magenta = "$($colors.bright_magenta)"
cyan    = "$($colors.bright_cyan)"
white   = "$($colors.bright_foreground)"
"@
Set-Content -Path 'alacritty/.config/alacritty/colors.toml' -Value $alacrittyColors
Write-Host "    -> alacritty/.config/alacritty/colors.toml (imported by alacritty.toml)"

Write-Host "==> Done. Re-run after editing themes/$Theme/colors.toml, or with -Theme <other> to switch themes."
